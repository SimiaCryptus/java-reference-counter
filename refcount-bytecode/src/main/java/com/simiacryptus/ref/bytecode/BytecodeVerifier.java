package com.simiacryptus.ref.bytecode;

import com.simiacryptus.ref.bytecode.model.BytecodeTypeIndex;
import com.simiacryptus.ref.bytecode.model.ClassMetadata;
import com.simiacryptus.ref.bytecode.verify.FieldLifecycleVerifier;
import com.simiacryptus.ref.bytecode.verify.HierarchyVerifier;
import com.simiacryptus.ref.bytecode.verify.MethodDataflowVerifier;
import com.simiacryptus.ref.lang.RefIgnore;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import javax.annotation.Nonnull;
import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.*;

/**
 * Entry point for reference-counting bytecode analysis and verification across compiled JVM classes,
 * directories, and JAR archives (Java, Kotlin, Scala, Groovy, and generated bytecode).
 */
@RefIgnore
public final class BytecodeVerifier {
  private static final Logger logger = LoggerFactory.getLogger(BytecodeVerifier.class);

  @Nonnull
  private final VerifierConfig config;

  public BytecodeVerifier() {
    this(VerifierConfig.defaults());
  }

  public BytecodeVerifier(@Nonnull VerifierConfig config) {
    this.config = Objects.requireNonNull(config, "config");
  }

  @Nonnull
  public VerifierConfig getConfig() {
    return config;
  }

  @Nonnull
  public VerificationResult analyze(@Nonnull Collection<File> targets, @Nonnull Collection<File> classpath) throws IOException {
    try (BytecodeTypeIndex index = new BytecodeTypeIndex(config.getClassLoader())) {
      for (File cp : classpath) {
        if (cp != null && cp.exists()) {
          index.addClasspathEntry(cp);
        }
      }
      for (File target : targets) {
        if (target != null && target.exists()) {
          index.addTargetFile(target);
        }
      }
      return runIndexAnalysis(index);
    }
  }

  @Nonnull
  public VerificationResult analyzeBytes(@Nonnull Collection<byte[]> targetClassBytes) {
    try (BytecodeTypeIndex index = new BytecodeTypeIndex(config.getClassLoader())) {
      for (byte[] bytes : targetClassBytes) {
        index.addTargetBytes(bytes, "<memory>");
      }
      return runIndexAnalysis(index);
    }
  }

  @Nonnull
  public VerificationResult analyzeBytes(@Nonnull Map<String, byte[]> targetClassBytesByOrigin) {
    try (BytecodeTypeIndex index = new BytecodeTypeIndex(config.getClassLoader())) {
      for (Map.Entry<String, byte[]> entry : targetClassBytesByOrigin.entrySet()) {
        index.addTargetBytes(entry.getValue(), entry.getKey());
      }
      return runIndexAnalysis(index);
    }
  }

  public void verify(@Nonnull Collection<File> targets, @Nonnull Collection<File> classpath) throws IOException {
    analyze(targets, classpath).throwIfErrors();
  }

  public void verifyBytes(@Nonnull Collection<byte[]> targetClassBytes) {
    analyzeBytes(targetClassBytes).throwIfErrors();
  }

  @Nonnull
  private VerificationResult runIndexAnalysis(@Nonnull BytecodeTypeIndex index) {
    List<Diagnostic> diagnostics = new ArrayList<>();
    Map<SourceLanguage, Integer> languageCounts = new EnumMap<>(SourceLanguage.class);
    int analyzedClasses = 0;
    int analyzedMethods = 0;
    int refCountedClasses = 0;

    HierarchyVerifier hierarchyVerifier = new HierarchyVerifier(index);
    FieldLifecycleVerifier fieldVerifier = new FieldLifecycleVerifier(index);
    MethodDataflowVerifier dataflowVerifier = new MethodDataflowVerifier(index, config);

    for (ClassMetadata cls : index.getTargetClasses()) {
      if (config.isExcluded(cls.getInternalName()) || cls.isModuleInfo()) {
        continue;
      }
      analyzedClasses++;
      languageCounts.merge(cls.getLanguage(), 1, Integer::sum);
      if (index.isReferenceCountingClass(cls.getInternalName())) {
        refCountedClasses++;
      }

      hierarchyVerifier.verify(cls, diagnostics);
      if (!config.isCheckOnly()) {
        fieldVerifier.verify(cls, diagnostics);
        analyzedMethods += dataflowVerifier.verifyClass(cls, diagnostics);
      }
    }

    return new VerificationResult(
        diagnostics,
        analyzedClasses,
        analyzedMethods,
        refCountedClasses,
        languageCounts
    );
  }

  /**
   * Executes the CLI arguments and returns the {@link VerificationResult}, writing any requested report file.
   */
  @Nonnull
  public static VerificationResult runCli(@Nonnull String[] args) throws IOException {
    if (args.length == 0) {
      throw new IllegalArgumentException(usage());
    }
    VerifierConfig.Builder configBuilder = VerifierConfig.builder();
    List<File> targets = new ArrayList<>();
    List<File> classpath = new ArrayList<>();
    Path reportOutput = null;

    for (int i = 0; i < args.length; i++) {
      String arg = args[i];
      switch (arg) {
        case "--check-only":
          configBuilder.checkOnly(true);
          break;
        case "--no-strict-blind":
          configBuilder.strictBlindParameters(false);
          break;
        case "-cp":
        case "--classpath":
          if (i + 1 >= args.length) {
            throw new IllegalArgumentException("Missing argument for " + arg + "\n" + usage());
          }
          for (String part : args[++i].split(File.pathSeparator)) {
            if (!part.isBlank()) {
              classpath.add(new File(part));
            }
          }
          break;
        case "--exclude-package":
          if (i + 1 >= args.length) {
            throw new IllegalArgumentException("Missing argument for --exclude-package\n" + usage());
          }
          configBuilder.excludePackage(args[++i]);
          break;
        case "--exclude-class":
          if (i + 1 >= args.length) {
            throw new IllegalArgumentException("Missing argument for --exclude-class\n" + usage());
          }
          configBuilder.excludeClass(args[++i]);
          break;
        case "--report":
          if (i + 1 >= args.length) {
            throw new IllegalArgumentException("Missing argument for --report\n" + usage());
          }
          reportOutput = Path.of(args[++i]);
          break;
        default:
          if (arg.startsWith("-")) {
            throw new IllegalArgumentException("Unknown option: " + arg + "\n" + usage());
          }
          targets.add(new File(arg));
          break;
      }
    }

    if (targets.isEmpty()) {
      throw new IllegalArgumentException("At least one target .class, directory, or .jar is required.\n" + usage());
    }

    BytecodeVerifier verifier = new BytecodeVerifier(configBuilder.build());
    VerificationResult result = verifier.analyze(targets, classpath);

    if (reportOutput != null) {
      Path parent = reportOutput.getParent();
      if (parent != null) {
        Files.createDirectories(parent);
      }
      String content = reportOutput.toString().toLowerCase().endsWith(".json")
          ? result.toJson()
          : result.formatReport();
      Files.writeString(reportOutput, content, StandardCharsets.UTF_8);
    }

    logger.info("{}", result.formatSummary());
    return result;
  }

  public static void main(String[] args) throws IOException {
    VerificationResult result = runCli(args);
    System.out.println(result.formatSummary());
    if (result.hasErrors()) {
      System.err.println(result.formatReport());
      throw new BytecodeVerificationException(result);
    }
  }

  @Nonnull
  private static String usage() {
    return "Usage: BytecodeVerifier [--classpath|-cp <paths>] [--check-only] [--no-strict-blind] "
        + "[--exclude-package <pkg>] [--exclude-class <cls>] [--report <file.txt|file.json>] <target1> [target2 ...]";
  }
}
